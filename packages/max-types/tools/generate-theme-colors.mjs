// Writes theme-colors.d.ts: every dynamic color name Max's themes define, with the label and
// category Max's color picker shows for it, so max.getcolor() can autocomplete them.
//
// Usage: node tools/generate-theme-colors.mjs [themes folder]
// The folder defaults to the Max 9 install's resources/interfaces/themes. Run it again after a
// Max update that adds colors.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_THEMES =
  process.platform == "win32"
    ? "C:/Program Files/Cycling '74/Max 9/resources/interfaces/themes"
    : "/Applications/Max.app/Contents/Resources/C74/interfaces/themes";

const themes = process.argv[2] ?? DEFAULT_THEMES;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "theme-colors.d.ts");

/** id -> { label, category }, from the first theme that labels it */
const colors = new Map();

function collect(node) {
  if (Array.isArray(node)) {
    node.forEach(collect);
  } else if (node && typeof node == "object") {
    if (typeof node.id == "string" && typeof node.label == "string" && !colors.has(node.id)) {
      colors.set(node.id, { label: node.label, category: node.category ?? "" });
    }
    Object.values(node).forEach(collect);
  }
}

const files = readdirSync(themes).filter((name) => name.endsWith(".maxtheme")).sort();
if (!files.length) {
  console.error(`no .maxtheme files in ${themes}`);
  process.exit(1);
}
for (const name of files) {
  collect(JSON.parse(readFileSync(join(themes, name), "utf8")));
}

const comment = (text) => text.replace(/\*\//g, "*\\/");
const sorted = [...colors].sort(([a], [b]) => a.localeCompare(b));

const lines = [
  "// Generated by tools/generate-theme-colors.mjs from Max 9's .maxtheme files; do not edit.",
  "",
  "/**",
  " * The dynamic colors Max's themes define, by the name max.getcolor() takes. Each one's",
  " * comment is the label (and category) Max's color picker shows. In a Max for Live device the",
  ' * "Live Theme Colors" (live_*) follow Live\'s theme.',
  " */",
  "interface ThemeColors {",
  ...sorted.flatMap(([id, { label, category }]) => [
    `  /** ${comment(label)}${category ? ` (${comment(category)})` : ""} */`,
    `  ${id}: true;`,
  ]),
  "}",
  "",
  "/** A dynamic color name for max.getcolor(); see ThemeColors. */",
  "type ThemeColor = keyof ThemeColors;",
  "",
];

writeFileSync(out, lines.join("\n"));
console.log(`${sorted.length} colors from ${files.length} themes -> ${out}`);
